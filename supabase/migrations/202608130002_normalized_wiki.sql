insert into public.catalog_entry_attributes (entry_id, label, value, sort_order)
select
  entry.id,
  attribute.value ->> 0,
  coalesce(attribute.value ->> 1, ''),
  attribute.ordinality::integer - 1
from public.catalog_entries as entry
cross join lateral jsonb_array_elements(entry.attributes) with ordinality as attribute(value, ordinality)
where jsonb_typeof(attribute.value) = 'array'
  and jsonb_array_length(attribute.value) >= 1
on conflict (entry_id, sort_order) do update
set label = excluded.label,
    value = excluded.value;

insert into public.catalog_entry_sections (entry_id, heading, body, sort_order)
select
  entry.id,
  null,
  detail.value #>> '{}',
  detail.ordinality::integer - 1
from public.catalog_entries as entry
cross join lateral jsonb_array_elements(entry.details) with ordinality as detail(value, ordinality)
where jsonb_typeof(detail.value) = 'string'
on conflict (entry_id, sort_order) do update
set body = excluded.body;

insert into public.catalog_media (entry_id, path, alt_text, is_primary, sort_order)
select id, image_path, name, true, 0
from public.catalog_entries
where image_path is not null
on conflict (entry_id, path) do update
set alt_text = excluded.alt_text,
    is_primary = true,
    sort_order = 0;

insert into public.recipes (source_id, name, summary)
select distinct on (source_id) source_id, name, summary
from public.gu_recipes
order by source_id, id
on conflict (source_id) do update
set name = excluded.name,
    summary = excluded.summary;

insert into public.recipe_outputs (recipe_id, entry_id, is_primary, match_method, confidence)
select distinct
  recipe.id,
  legacy.gu_entry_id,
  false,
  case
    when legacy.source_id like entry.source_id || '%' then 'source-id-prefix'
    when entry.source_id like regexp_replace(legacy.source_id, '(?:_?gu)?_?gu_?fang$', '', 'i') || '%' then 'source-id-prefix'
    else 'name-heuristic'
  end,
  case
    when legacy.source_id like entry.source_id || '%' then 100
    when entry.source_id like regexp_replace(legacy.source_id, '(?:_?gu)?_?gu_?fang$', '', 'i') || '%' then 90
    else 50
  end
from public.gu_recipes as legacy
join public.recipes as recipe on recipe.source_id = legacy.source_id
join public.catalog_entries as entry on entry.id = legacy.gu_entry_id
on conflict (recipe_id, entry_id) do update
set match_method = excluded.match_method,
    confidence = excluded.confidence;

with canonical_legacy_recipe as (
  select distinct on (source_id) id as legacy_id, source_id
  from public.gu_recipes
  order by source_id, id
)
insert into public.recipe_components (recipe_id, position, raw_text)
select recipe.id, ingredient.position, ingredient.description
from canonical_legacy_recipe as canonical
join public.recipes as recipe on recipe.source_id = canonical.source_id
join public.recipe_ingredients as ingredient on ingredient.recipe_id = canonical.legacy_id
on conflict (recipe_id, position) do update
set raw_text = excluded.raw_text;

