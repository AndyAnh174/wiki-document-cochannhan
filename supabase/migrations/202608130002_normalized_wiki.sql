create or replace function public.search_catalog(
  p_query text default null,
  p_kind text default null,
  p_category text default null,
  p_limit integer default 24,
  p_offset integer default 0
)
returns table (
  id bigint,
  kind text,
  source_id text,
  slug text,
  name text,
  image_path text,
  category text,
  rank text,
  summary text,
  total_count bigint
)
language sql
stable
security invoker
set search_path = ''
as $$
  select
    entry.id,
    entry.kind,
    entry.source_id,
    entry.slug,
    entry.name,
    entry.image_path,
    entry.category,
    entry.rank,
    entry.summary,
    count(*) over() as total_count
  from public.catalog_entries as entry
  where entry.is_published
    and (p_kind is null or entry.kind = p_kind)
    and (p_category is null or entry.category = p_category)
    and (
      nullif(trim(p_query), '') is null
      or entry.search_text ilike '%' || trim(p_query) || '%'
      or entry.search_text operator(public.%) trim(p_query)
    )
  order by
    case
      when nullif(trim(p_query), '') is null then 0
      else public.similarity(entry.search_text, trim(p_query))
    end desc,
    entry.name asc
  limit least(greatest(p_limit, 1), 100)
  offset greatest(p_offset, 0);
$$;

grant execute on function public.search_catalog(text, text, text, integer, integer)
to anon, authenticated;

